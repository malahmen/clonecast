//go:build ignore

// gen_codes writes codes_table.go: go-evdev's KEYNames and KEYFromString maps,
// copied with plain numeric codes so package keys does not import go-evdev
// (which does not build for Windows). It reads codes.go from the go-evdev
// version in go.sum and evaluates the constants with go/types, so aliases such
// as KEY_MIN_INTERESTING = KEY_MUTE resolve exactly as the compiler would.
//
// Run with `go generate ./internal/keys` (Kamino 278).
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/constant"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const module = "github.com/holoplot/go-evdev"

func main() {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", module).Output()
	if err != nil {
		log.Fatalf("go list %s: %v", module, err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(out)), " ")
	if dir == "" {
		log.Fatalf("go list %s: module not in the module cache (run go mod download)", module)
	}
	path := filepath.Join(dir, "codes.go")

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	if err != nil {
		log.Fatal(err)
	}
	// Type-check codes.go on its own. EvCode and friends live in types.go and
	// are reported as undefined; the untyped constants still get their values,
	// which is all this needs.
	conf := types.Config{Error: func(error) {}}
	pkg, _ := conf.Check("evdev", fset, []*ast.File{file}, nil)

	value := func(e ast.Expr) uint16 {
		id, ok := e.(*ast.Ident)
		if !ok {
			log.Fatalf("%s: not an identifier", fset.Position(e.Pos()))
		}
		c, ok := pkg.Scope().Lookup(id.Name).(*types.Const)
		if !ok {
			log.Fatalf("%s: %s is not a constant", fset.Position(e.Pos()), id.Name)
		}
		v, ok := constant.Uint64Val(c.Val())
		if !ok || v > 0xffff {
			log.Fatalf("%s: %s = %s does not fit a uint16", fset.Position(e.Pos()), id.Name, c.Val())
		}
		return uint16(v)
	}
	str := func(e ast.Expr) string {
		lit, ok := e.(*ast.BasicLit)
		if !ok || lit.Kind != token.STRING {
			log.Fatalf("%s: not a string literal", fset.Position(e.Pos()))
		}
		s, err := strconv.Unquote(lit.Value)
		if err != nil {
			log.Fatal(err)
		}
		return s
	}
	elems := func(name string) []*ast.KeyValueExpr {
		for _, d := range file.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != token.VAR {
				continue
			}
			for _, s := range g.Specs {
				vs := s.(*ast.ValueSpec)
				if len(vs.Names) != 1 || vs.Names[0].Name != name {
					continue
				}
				lit := vs.Values[0].(*ast.CompositeLit)
				kvs := make([]*ast.KeyValueExpr, len(lit.Elts))
				for i, e := range lit.Elts {
					kvs[i] = e.(*ast.KeyValueExpr)
				}
				return kvs
			}
		}
		log.Fatalf("%s: no var %s", path, name)
		return nil
	}

	type entry struct {
		code uint16
		name string
	}
	var names, parse []entry
	for _, kv := range elems("KEYNames") {
		names = append(names, entry{value(kv.Key), str(kv.Value)})
	}
	for _, kv := range elems("KEYFromString") {
		parse = append(parse, entry{value(kv.Value), str(kv.Key)})
	}
	sort.Slice(names, func(i, j int) bool { return names[i].code < names[j].code })
	sort.Slice(parse, func(i, j int) bool {
		if parse[i].code != parse[j].code {
			return parse[i].code < parse[j].code
		}
		return parse[i].name < parse[j].name
	})

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen_codes.go from %s@%s codes.go. DO NOT EDIT.\n\n", module, version)
	fmt.Fprintf(&b, "package keys\n\n")
	fmt.Fprintf(&b, "// keyNames is go-evdev's KEYNames: one display name per code. A code with\n")
	fmt.Fprintf(&b, "// several kernel names gets them joined with \"/\", as go-evdev does.\n")
	fmt.Fprintf(&b, "var keyNames = map[Code]string{\n")
	for _, e := range names {
		fmt.Fprintf(&b, "\t0x%03x: %q,\n", e.code, e.name)
	}
	fmt.Fprintf(&b, "}\n\n")
	fmt.Fprintf(&b, "// keyFromString is go-evdev's KEYFromString: every kernel name, aliases\n")
	fmt.Fprintf(&b, "// included, to its code.\n")
	fmt.Fprintf(&b, "var keyFromString = map[string]Code{\n")
	for _, e := range parse {
		fmt.Fprintf(&b, "\t%q: 0x%03x,\n", e.name, e.code)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("codes_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
